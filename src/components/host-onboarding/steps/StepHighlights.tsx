interface Props {
  data: HostFormData;
  onChange: (updates: Partial<HostFormData>) => void;
}

export function StepHighlights({ data, onChange }: Props) {
  const toggle = (id: string) => {
    const updated = data.highlights.includes(id)
      ? data.highlights.filter((h) => h !== id)
      : data.highlights.length < 2 
        ? [...data.highlights, id]
        : data.highlights;
    onChange({ highlights: updated });
  };

  return (
    <div className="max-w-2xl mx-auto px-6 py-12">
      {/* Title and subtext matching image spacing */}
      <h1 className="text-[32px] font-bold text-[#222222] mb-3 leading-tight">
        Next, let's describe your house
      </h1>
      <p className="text-[#717171] text-base mb-10">
        Choose up to 2 highlights. We'll use these to get your description started.
      </p>

      {/* Button Group with wrap gap matching the design */}
      <div className="flex flex-wrap gap-4">
        {highlightOptions.map((h) => {
          const isSelected = data.highlights.includes(h.id);
          return (
            <button
              key={h.id}
              type="button"
              onClick={() => toggle(h.id)}
              className={cn(
                "flex items-center gap-2 px-5 py-3 rounded-full border transition-all duration-200 text-base font-semibold",
                isSelected
                  ? "border-black bg-[#F7F7F7] text-black ring-1 ring-black"
                  : "border-[#DDDDDD] text-[#222222] bg-white hover:border-black"
              )}
            >
              {/* Icon color shifts when selected */}
              <span className={cn(isSelected ? "text-black" : "text-[#222222]")}>
                {h.icon}
              </span>
              {h.label}
            </button>
          );
        })}
      </div>
    </div>
  );
}
